def unit_docs(unit):
    """systemd man page for a unit (systemd-* units have their own page)."""
    base = "https://www.freedesktop.org/software/systemd/man/latest"
    if unit.startswith("systemd-"):
        return f"{base}/{unit}.html"
    kind = unit.rsplit(".", 1)[-1]
    return f"{base}/systemd.special.html" if kind == "target" else f"{base}/systemd.{kind}.html"


class SourceIndex:
    """function -> (absolute path, line) for one build, via vmlinux DWARF (nm + addr2line),
    falling back to `git grep` for functions without a symbol (inlined static helpers).
    Results are cached in builds/<b>/lab-sources.json, keyed by the vmlinux identity."""

    def __init__(self, build):
        meta = build_meta(build)
        self.vmlinux = build_dir(build) / "vmlinux"
        self.cache_file = build_dir(build) / "lab-sources.json"
        self.tree = tree_path(meta["tree"]) if meta.get("tree") else None
        base = output(["git", "-C", self.tree, "describe", "--tags", "--abbrev=0"]) if self.tree else ""
        self.tag = base if re.fullmatch(r"v\d+\.\d+(\.\d+)?(-rc\d+)?", base) else None
        st = self.vmlinux.stat() if self.vmlinux.exists() else None
        self.key = f"{st.st_mtime_ns}-{st.st_size}" if st else ""
        self.map = {}
        try:
            cached = json.loads(self.cache_file.read_text())
            if cached.get("vmlinux") == self.key:
                self.map = cached["functions"]
        except (OSError, ValueError, KeyError):
            pass

    def resolve(self, wanted):
        """wanted: {(function, size)}; fills self.map for the ones not cached yet."""
        todo = {(f, sz) for f, sz in wanted if f and f"{f}/{sz}" not in self.map}
        if not todo or not self.key:
            return
        syms = {}
        names = {f for f, _ in todo}
        nm = subprocess.run(["nm", "-S", "--defined-only", self.vmlinux],
                            capture_output=True, text=True).stdout
        for line in nm.splitlines():
            parts = line.split()
            if len(parts) == 4 and parts[3] in names and parts[2] in "tT":
                syms.setdefault(parts[3], []).append((parts[0], int(parts[1], 16)))
        addr_of = {}
        for f, sz in todo:
            cands = syms.get(f)
            if cands:
                # Duplicate static names: the trace's size (padded) is >= the symbol size.
                fit = [c for c in cands if not sz or c[1] <= sz]
                addr_of[(f, sz)] = max(fit or cands, key=lambda c: c[1])[0]
        if addr_of:
            # addr2line costs ~25 ms/address on compressed DWARF; contiguous address ranges in
            # parallel processes cut a cold lookup of ~750 initcalls from ~20 s to ~5 s.
            keys = sorted(addr_of, key=addr_of.get)
            n = max(1, min(12, os.cpu_count() or 1, len(keys) // 20))
            chunks = [keys[i * len(keys) // n:(i + 1) * len(keys) // n] for i in range(n)]
            with ThreadPoolExecutor(n) as ex:
                outs = ex.map(lambda c: subprocess.run(
                    ["addr2line", "-e", self.vmlinux, *[addr_of[k] for k in c]],
                    capture_output=True, text=True).stdout.splitlines(), chunks)
                pairs = [p for c, o in zip(chunks, outs) for p in zip(c, o)]
            for k, line in pairs:
                path, _, ln = line.split(" ")[0].rpartition(":")
                if path and path != "??" and ln.isdigit() and ln != "0":
                    self.map[f"{k[0]}/{k[1]}"] = [path, int(ln)]
        for f, sz in todo:
            if f"{f}/{sz}" not in self.map and self.tree:
                hit = self._grep(f)
                if hit:
                    self.map[f"{f}/{sz}"] = hit
        try:
            self.cache_file.write_text(json.dumps({"vmlinux": self.key, "functions": self.map}))
        except OSError:
            pass

    def _grep(self, fn):
        out = output(["git", "-C", self.tree, "grep", "-n", "-E", rf"^[A-Za-z_].*[ *]{fn}\(",
                      "--", "*.c"])
        for line in out.splitlines():
            path, ln, text = line.split(":", 2)
            if text.rstrip().endswith(";") or (path.startswith("arch/") and
                                               not path.startswith("arch/x86/")):
                continue
            return [str(self.tree / path), int(ln)]
        return None

    def attrs(self, fn, size=0):
        hit = self.map.get(f"{fn}/{size}")
        if not hit:
            return {}
        path, line = hit
        a = {"code.function": fn, "code.lineno": line,
             "link.vscode": f"{CODE_LINKS_URL}/code?"
                            + urllib.parse.urlencode({"path": path, "line": line}, safe="/")}
        rel = None
        if self.tree and path.startswith(str(self.tree) + "/"):
            rel = path[len(str(self.tree)) + 1:]
        a["code.filepath"] = rel or path
        if rel and self.tag:
            a["link.elixir"] = f"https://elixir.bootlin.com/linux/{self.tag}/source/{rel}#L{line}"
        return a


def attach_sources(spans, build):
    """Add code.* attributes and clickable source links to every span that has code."""
    idx = SourceIndex(build)
    idx.resolve({sp.code for sp in spans if sp.code})
    linked = 0
    for sp in spans:
        if sp.code:
            a = idx.attrs(*sp.code)
            sp.attrs.update(a)
            linked += bool(a)
    return linked


