TS_RE = re.compile(r"^\[\s*(\d+\.\d+)\]")
TRACE_RE = re.compile(r"\s(\d+\.\d+): (initcall_level|initcall_start|initcall_finish): (.*)$")


# --------------------------------------------------------------------------- parsing

def _fn(raw):
    return raw.split("+", 1)[0]


def parse_trace(text):
    """-> (levels [(name, start)], initcalls [{fn, level, start, end, ret}]) in seconds."""
    levels, calls, open_calls = [], [], {}
    for line in text.splitlines():
        m = TRACE_RE.search(line)
        if not m:
            continue
        ts, ev, rest = float(m.group(1)), m.group(2), m.group(3)
        kv = dict(p.split("=", 1) for p in rest.split() if "=" in p)
        if ev == "initcall_level":
            levels.append((kv.get("level", "?"), ts))
        elif ev == "initcall_start":
            open_calls[kv["func"]] = (ts, levels[-1][0] if levels else "?")
        elif ev == "initcall_finish" and kv.get("func") in open_calls:
            start, level = open_calls.pop(kv["func"])
            size = kv["func"].rsplit("/", 1)[-1]
            calls.append({"fn": _fn(kv["func"]), "level": level, "start": start, "end": ts,
                          "ret": int(kv.get("ret", 0)),
                          "size": int(size, 16) if size.startswith("0x") else 0})
    return levels, calls


def parse_milestones(dmesg):
    out = []
    for name, pat in MILESTONES:
        rx = re.compile(pat)
        for line in dmesg.splitlines():
            m = TS_RE.match(line)
            if m and rx.search(line):
                out.append((name, float(m.group(1)), line[m.end():].strip()[:200]))
                break
    return sorted(out, key=lambda x: x[1])


def parse_units(text):
    """systemctl show blocks -> [{unit, start, end}] in seconds since boot."""
    units = []
    for block in text.strip().split("\n\n"):
        kv = dict(l.split("=", 1) for l in block.splitlines() if "=" in l)
        try:
            start = int(kv.get("InactiveExitTimestampMonotonic", 0))
            end = int(kv.get("ActiveEnterTimestampMonotonic", 0))
        except ValueError:
            continue
        if start and end and end >= start:
            units.append({"unit": kv.get("Id", "?"), "start": start / 1e6, "end": end / 1e6})
    return sorted(units, key=lambda u: u["start"])


def parse_sa_time(text):
    """'Startup finished in 652ms (kernel) + 1.168s (userspace) = …' -> {kernel, userspace}."""
    def secs(tok):
        total = 0.0
        for num, unit in re.findall(r"([\d.]+)(min|ms|us|s)\b", tok):
            total += float(num) * {"min": 60, "s": 1, "ms": 1e-3, "us": 1e-6}[unit]
        return total
    out = {}
    for part in ("kernel", "userspace"):
        m = re.search(r"([\d.a-z ]+?) \(" + part + r"\)", text)
        if m:
            out[part] = secs(m.group(1))
    return out


# --------------------------------------------------------------------------- model

class Span:
    def __init__(self, name, start, end, service, parent=None, attrs=None, events=None,
                 code=None):
        self.id = secrets.token_hex(8)
        self.code = code            # (function, symbol size or 0) to link to its source
        self.name, self.start, self.end, self.service = name, start, max(end, start), service
        self.parent, self.attrs, self.events = parent, attrs or {}, events or []


def build_spans(d):
    """Turn parsed boot data (seconds since kernel t=0) into a span tree."""
    levels, calls, units, miles = d["levels"], d["initcalls"], d["units"], d["milestones"]
    kernel_end = next((t for n, t, _ in miles if n == "exec /sbin/init"), None) \
        or (calls[-1]["end"] if calls else d["sa"].get("kernel", 0))
    user_end = max([u["end"] for u in units] + [kernel_end + d["sa"].get("userspace", 0)])
    pre = d["prekernel"]

    root = Span(f"boot {d['build']}", -pre if pre else 0, user_end, "lab",
                attrs={"build": d["build"], "kernel.release": d["release"], "run": d["run"],
                       "cmdline": d["cmdline"]})
    spans = [root]
    if pre:
        spans.append(Span("pre-kernel: QEMU, firmware, load + decompress", -pre, 0, "firmware",
                          root.id, {"note": "host-measured: QEMU start to kernel t=0 (approx.)"}))
    kernel = Span("kernel", 0, kernel_end, "kernel", root.id,
                  attrs={"initcalls": len(calls)},
                  events=[(t, n, line) for n, t, line in miles])
    spans.append(kernel)

    # A level runs from its initcall_level event to the end of its last initcall.
    bounds = []
    for name, start in levels:
        in_level = [c for c in calls if c["level"] == name]
        bounds.append((name, start, max([start] + [c["end"] for c in in_level])))
    by_name = {n: (s, e) for n, s, e in bounds}

    def phase(name, start, end, attrs=None):
        if start is not None and end is not None and end >= start:
            s = Span(name, start, end, "kernel", kernel.id, attrs)
            spans.append(s)
            return s
        return None

    early = by_name.get("early")
    pure = by_name.get("pure")
    last = bounds[-1] if bounds else None
    phase("start_kernel: arch, mm, sched, irq, timers", 0, early[0] if early else None,
          {"see": "init/main.c:start_kernel()"})
    if early and pure:
        phase("SMP bring-up + driver core (smp_init, driver_init)", early[1], pure[0],
              {"see": "init/main.c:kernel_init_freeable()"})
    if last:
        tail = phase("after initcalls: devices, root fs, exec /sbin/init", last[2], kernel_end,
                     {"see": "init/main.c:kernel_init(), init/do_mounts.c:prepare_namespace()"})
        mark = {n: t for n, t, _ in miles}
        probed = mark.get("async device probes done (md autodetect starts)")
        mounted = mark.get("root fs mounted")
        cuts = [("wait for async device probes (wait_for_device_probe)", last[2], probed),
                ("mount root filesystem", probed or last[2], mounted),
                ("free init memory, mark rodata RO, exec init", mounted, kernel_end)]
        for name, a, b in cuts:
            if tail and a is not None and b is not None and b >= a:
                spans.append(Span(name, a, b, "kernel", tail.id))

    level_spans = {}
    for name, start, end in bounds:
        idx = LEVELS.index(name) if name in LEVELS else 99
        n = sum(1 for c in calls if c["level"] == name)
        level_spans[name] = phase(f"initcalls: {name}", start, end,
                                  {"level": name, "order": idx, "initcalls": n})
    for c in calls:
        parent = level_spans.get(c["level"]) or kernel
        spans.append(Span(c["fn"], c["start"], c["end"], "kernel", parent.id,
                          {"level": c["level"], "ret": c["ret"],
                           "duration_us": round((c["end"] - c["start"]) * 1e6)},
                          code=(c["fn"], c.get("size", 0))))

    user = Span("userspace (systemd)", kernel_end, user_end, "systemd", root.id,
                {"units": len(units)})
    spans.append(user)
    for u in units:
        spans.append(Span(u["unit"], u["start"], u["end"], "systemd", user.id,
                          {"duration_ms": round((u["end"] - u["start"]) * 1e3, 3)}))
    for sp in spans:
        if sp.code is None:
            fn = PHASE_CODE.get(sp.name) or ("do_initcall_level" if sp.name.startswith("initcalls:")
                                             else None)
            sp.code = (fn, 0) if fn else None
        if sp.service == "systemd" and sp.parent == user.id:
            sp.attrs["link.docs"] = unit_docs(sp.name)
    return spans, {"prekernel": pre, "kernel": kernel_end, "userspace": user_end - kernel_end,
                   "total": user_end + (pre or 0)}


