"""`lab boottrace`: record every step of a boot and show it as a trace.

The guest is booted with the kernel's initcall tracepoints enabled
(trace_event=initcall:*), then a job collects the ftrace buffer, dmesg and systemd unit
timestamps. Combined with host-side timing (QEMU start vs. arrival of console lines) this
becomes one trace:

    boot <build>
    ├─ pre-kernel        QEMU start, firmware, kernel load + decompression (host-measured)
    ├─ kernel
    │  ├─ start_kernel   arch/mm/sched/irq/timer setup (+ console initcalls)
    │  ├─ early initcalls (pre-SMP)
    │  ├─ SMP bring-up + driver core
    │  ├─ initcalls: pure … late   → one span per initcall (µs exact)
    │  └─ mount root, free init memory, exec /sbin/init
    └─ userspace         one span per systemd unit (activating → active)

Traces go to Tempo (OTLP/HTTP), summary metrics to VictoriaMetrics, everything also to
runs/<id>/ (result.json is `lab compare`-compatible: kernel/userspace/pre-kernel times).
"""

