def _attr(k, v):
    if isinstance(v, bool):
        val = {"boolValue": v}
    elif isinstance(v, int):
        val = {"intValue": str(v)}
    elif isinstance(v, float):
        val = {"doubleValue": v}
    else:
        val = {"stringValue": str(v)}
    return {"key": k, "value": val}


def otlp(spans, trace_id, t0_ns):
    """OTLP/JSON payload; span times are seconds relative to kernel t=0."""
    ns = lambda t: str(t0_ns + int(round(t * 1e9)))
    by_service = {}
    for s in spans:
        span = {"traceId": trace_id, "spanId": s.id, "name": s.name, "kind": 1,
                "startTimeUnixNano": ns(s.start), "endTimeUnixNano": ns(s.end),
                "attributes": [_attr(k, v) for k, v in s.attrs.items()]}
        if s.parent:
            span["parentSpanId"] = s.parent
        if s.events:
            span["events"] = [{"timeUnixNano": ns(t), "name": n,
                               "attributes": [_attr("log", line)]} for t, n, line in s.events]
        by_service.setdefault(s.service, []).append(span)
    return {"resourceSpans": [
        {"resource": {"attributes": [_attr("service.name", svc)]},
         "scopeSpans": [{"scope": {"name": "klab.boottrace"}, "spans": sp}]}
        for svc, sp in by_service.items()]}


def push_metrics(d, phases, trace_id):
    ts = int(time.time() * 1000)
    L = observe._labels
    base = {"run": d["run"], "build": d["build"]}
    lines = [f'lab_boot_info{L({**base, "kernel": d["release"], "trace_id": trace_id})} 1 {ts}']
    for k, v in phases.items():
        if v:
            lines.append(f'lab_boot_seconds{L({**base, "phase": k})} {v} {ts}')
    for name, start, end, n in d["level_summary"]:
        idx = LEVELS.index(name) if name in LEVELS else 99
        lines.append(f'lab_boot_level_seconds{L({**base, "level": f"{idx:02d} {name}"})} '
                     f'{end - start} {ts}')
    for c in d["initcalls"]:
        lab = {**base, "fn": c["fn"], "level": c["level"]}
        lines.append(f'lab_boot_initcall_seconds{L(lab)} {c["end"] - c["start"]} {ts}')
    for u in d["units"]:
        lines.append(f'lab_boot_unit_seconds{L({**base, "unit": u["unit"]})} '
                     f'{u["end"] - u["start"]} {ts}')
    observe.push(lines)


def tempo_available(wait=60):
    """True once Tempo is ready. A freshly (re)started Tempo answers but reports not-ready
    for ~15 s, so wait for it instead of silently skipping the trace."""
    deadline = time.monotonic() + wait
    announced = False
    while True:
        try:
            observe._request("GET", f"{TEMPO_URL}/ready", timeout=2)
            return True
        except urllib.error.HTTPError:        # up, still starting (503)
            if not announced:
                info("waiting for Tempo to become ready ...")
                announced = True
        except (OSError, urllib.error.URLError):
            return False                      # not running at all
        if time.monotonic() > deadline:
            return False
        time.sleep(1)


def tempo_has(trace_id):
    """Tempo returns 200 with an empty body for unknown IDs, so check the content."""
    try:
        body = observe._request("GET", f"{TEMPO_URL}/api/v2/traces/{trace_id}", timeout=10)
    except (OSError, urllib.error.URLError, ValueError):
        return False
    trace = body.get("trace", body) if isinstance(body, dict) else {}
    return bool(trace.get("resourceSpans") or trace.get("batches"))


def send_trace(payload):
    try:
        observe._request("POST", OTLP_URL, body=payload, timeout=30)
        return True
    except (OSError, urllib.error.URLError) as e:
        warn(f"sending trace to Tempo failed ({e})")
        return False


def resend(quiet=False):
    """Re-upload saved boot traces (runs/*/boot*/trace.otlp.json) that Tempo is missing,
    e.g. after a Tempo restart lost its newest block or a trace was skipped."""
    if not tempo_available():
        raise LabError("Tempo is not running (make observe)")
    sent = checked = 0
    for f in sorted(RUNS.glob("*/boot*/trace.otlp.json")):
        try:
            trace_id = json.loads((f.parent / "boot.json").read_text())["trace_id"]
        except (OSError, ValueError, KeyError):
            continue
        checked += 1
        if not tempo_has(trace_id) and send_trace(json.loads(f.read_text())):
            sent += 1
            if not quiet:
                info(f"re-sent {f.parent.parent.name}/{f.parent.name}")
    if sent or not quiet:
        info(f"boot traces: {checked} saved, {sent} re-sent to Tempo")
    return sent


