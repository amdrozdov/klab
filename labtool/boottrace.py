def boottrace(build=None, boots=1, cpus=DEFAULT_CPUS, mem=DEFAULT_MEM, pin=None, append="",
              label=None, timeout=300, no_telemetry=False, top=15):
    build = default_build(build)
    meta = build_meta(build)
    run_id = time.strftime("%Y%m%d-%H%M%S") + f"-{build}-boottrace" + (f"-{label}" if label else "")
    rundir = RUNS / run_id
    export = observe.wanted(no_telemetry)
    tempo = export and tempo_available()
    if export and not tempo:
        warn("Tempo is not up: metrics only. The trace is saved; upload it later with "
             "`lab boottrace --resend` (make observe does this automatically)")
    info(f"boottrace {run_id}: {boots} boot(s) with {TRACE_ARGS}")
    vm_kw = {"cpus": cpus, "mem": mem, "pin": pin, "append": f"{TRACE_ARGS} {append}".strip()}
    if common.DRY:
        run_job(build, rundir / "boot0", None, timeout, **vm_kw)
        return None
    rundir.mkdir(parents=True)

    values = {"prekernel": [], "kernel": [], "userspace": [], "total": []}
    last = None
    for n in range(boots):
        work = rundir / f"boot{n}"
        work.mkdir()
        (work / "job.sh").write_text(COLLECT_JOB)
        arrivals = []
        start_wall = time.time()
        run_job(build, work, rundir / f"console{n}.log", timeout,
                on_line=lambda l: arrivals.append((time.time(), l)), **vm_kw)
        if not (work / "trace.txt").exists():
            raise LabError(f"guest did not produce boot data; see {rundir}/console{n}.log")

        # Kernel t=0 on the wall clock: each console line "[ts] ..." arrived at or after
        # t0 + ts, so the smallest (arrival - ts) is the best estimate.
        t0 = min((a - float(m.group(1)) for a, l in arrivals
                  if (m := TS_RE.match(l.strip()))), default=None)
        levels, calls = parse_trace((work / "trace.txt").read_text(errors="replace"))
        d = {
            "run": run_id if boots == 1 else f"{run_id}-b{n}", "build": build,
            "release": (work / "kernel_release").read_text().strip(),
            "cmdline": (work / "cmdline").read_text().strip(),
            "levels": levels, "initcalls": calls,
            "milestones": parse_milestones((work / "dmesg.txt").read_text(errors="replace")),
            "units": parse_units((work / "units.txt").read_text(errors="replace")),
            "sa": parse_sa_time((work / "sa_time.txt").read_text(errors="replace")),
            "prekernel": (t0 - start_wall) if t0 else None,
        }
        spans, phases = build_spans(d)
        linked = attach_sources(spans, build)
        d["level_summary"] = [(s.attrs["level"], s.start, s.end, s.attrs["initcalls"])
                              for s in spans if "order" in s.attrs]
        trace_id = secrets.token_hex(16)
        t0_ns = int((t0 or start_wall) * 1e9)
        payload = otlp(spans, trace_id, t0_ns)
        (work / "trace.otlp.json").write_text(json.dumps(payload))
        (work / "boot.json").write_text(json.dumps(
            {**d, "phases": phases, "trace_id": trace_id}, indent=1, default=str))
        if tempo:
            send_trace(payload)
        if export:
            push_metrics(d, phases, trace_id)
        for k in values:
            if phases.get(k):
                values[k].append(phases[k])
        last = (d, phases, trace_id)
        info(f"boot {n + 1}/{boots}: kernel {phases['kernel'] * 1e3:.0f} ms, "
             f"userspace {phases['userspace'] * 1e3:.0f} ms, {len(calls)} initcalls, "
             f"{linked} spans linked to source")

    result = {
        "id": run_id, "label": label, "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "build": build, "tree": meta.get("tree"), "profile": meta.get("profile"),
        "commit": meta.get("commit"), "describe": meta.get("describe"),
        "config_hash": meta.get("config_hash"),
        "guest": {"kernel_release": last[0]["release"]},
        "vm": {"cpus": cpus, "mem": mem, "pin": pin, "append": vm_kw["append"]},
        "params": {"repeat": 1, "warmup": 0, "boots": boots},
        "telemetry": False,
        "results": {"boottrace": {k: {"unit": "s", "better": "lower", "values": v}
                                  for k, v in values.items() if v}},
    }
    (rundir / "result.json").write_text(json.dumps(result, indent=2) + "\n")
    report(*last, top=top)
    info(f"saved runs/{run_id}/ (boot*/boot.json, trace.otlp.json; `lab compare` works on it)")
    if export:
        info(f"Grafana: {observe.GRAFANA_URL}/d/lab-boot?var-build={build}&var-boot={last[0]['run']}")
    return run_id


def report(d, phases, trace_id, top=15):
    ms = lambda s: f"{s * 1e3:,.1f} ms" if s is not None else "?"
    print()
    print(table([[k, ms(phases.get(k))] for k in ("prekernel", "kernel", "userspace", "total")],
                ["phase", "time"]))
    print()
    print(table([[f"{s:8.3f}s", n] for n, s, _ in d["milestones"]], ["at", "kernel milestone"]))
    print()
    rows = [[name, f"{(end - start) * 1e3:,.1f} ms", n]
            for name, start, end, n in d["level_summary"]]
    print(table(rows, ["initcall level", "time", "initcalls"]))
    print()
    slow = sorted(d["initcalls"], key=lambda c: c["start"] - c["end"])[:top]
    print(table([[c["fn"], c["level"], f"{(c['end'] - c['start']) * 1e6:,.0f} us"] for c in slow],
                [f"slowest {top} initcalls", "level", "time"]))
    print()
    units = sorted(d["units"], key=lambda u: u["start"] - u["end"])[:top]
    print(table([[u["unit"], f"{(u['end'] - u['start']) * 1e3:,.1f} ms"] for u in units],
                [f"slowest {top} systemd units", "time"]))
